/** Locales suportados pelo produto (12 idiomas). pt-BR é a fonte canônica. */
export const SUPPORTED_LOCALES = [
	"pt-BR",
	"en",
	"es",
	"fr",
	"ru",
	"uk",
	"ja",
	"ko",
	"zh",
	"tr",
	"ar",
	"hi",
] as const;

/** Locale persistido: Settings grava em localStorage['user_data'].language
 * (user-preferences). Fallback pt-BR. */
function loadSavedLocale(): string {
	try {
		const stored = localStorage.getItem("user_data");
		if (stored) {
			const prefs = JSON.parse(stored);
			if (typeof prefs.language === "string") return prefs.language;
		}
	} catch {
		// localStorage indisponível — fallback abaixo
	}
	return "pt-BR";
}

const savedLocale = loadSavedLocale();

export default createI18n({
	legacy: false,
	locale: (SUPPORTED_LOCALES as readonly string[]).includes(savedLocale)
		? savedLocale
		: "pt-BR",
	fallbackLocale: "pt-BR",
	messages: {
		"pt-BR": { ...ptBR, ...modulesPtBR },
		en: { ...en, ...modulesEn },
		es: { ...es, ...modulesEs },
		fr: { ...fr, ...modulesFr },
		ru: { ...ru, ...modulesRu },
		uk: { ...uk, ...modulesUk },
		ja: { ...ja, ...modulesJa },
		ko: { ...ko, ...modulesKo },
		zh: { ...zh, ...modulesZh },
		tr: { ...tr, ...modulesTr },
		ar: { ...ar, ...modulesAr },
		hi: { ...hi, ...modulesHi },
	},
});
